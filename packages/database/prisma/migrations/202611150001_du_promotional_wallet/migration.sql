CREATE TABLE public.du_transactions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  seq bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  type varchar(10) NOT NULL,
  user_id uuid NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  stream_id uuid REFERENCES public.live_streams(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  creator_id uuid REFERENCES public.users(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  gift_id uuid REFERENCES public.du_gifts(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  quantity bigint,
  unit_price bigint,
  amount bigint NOT NULL,
  balance_after bigint NOT NULL CHECK (balance_after >= 0),
  idempotency_key varchar(200) NOT NULL CHECK (length(btrim(idempotency_key)) BETWEEN 1 AND 200),
  created_at timestamptz(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT du_transactions_user_id_idempotency_key_key UNIQUE(user_id,idempotency_key),
  CONSTRAINT du_transaction_shape CHECK (
    (type = 'CLAIM' AND amount = 100 AND stream_id IS NULL AND creator_id IS NULL
      AND gift_id IS NULL AND quantity IS NULL AND unit_price IS NULL)
    OR (type = 'GIFT' AND stream_id IS NOT NULL AND creator_id IS NOT NULL
      AND creator_id <> user_id AND gift_id IS NOT NULL AND quantity IS NOT NULL AND quantity BETWEEN 1 AND 99
      AND unit_price IS NOT NULL AND unit_price > 0 AND amount < 0 AND amount >= -9223372036854775807
      AND amount::numeric = -(quantity::numeric * unit_price::numeric))
  )
);
CREATE UNIQUE INDEX du_one_claim_per_user ON public.du_transactions(user_id) WHERE type = 'CLAIM';
CREATE INDEX du_transactions_user_id_seq_idx ON public.du_transactions(user_id,seq);
CREATE INDEX du_transactions_stream_id_seq_idx ON public.du_transactions(stream_id,seq);

